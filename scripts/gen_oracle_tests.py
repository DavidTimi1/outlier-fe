#!/usr/bin/env python3
"""
Oracle-to-Fe Conformance Test Generator (T2.8).

Imports the independent Python oracle (`oracle/outlier_model.py`) configured at the
production shipping parameters (`FINISH=4, PUSH=1, ROUND_CAP=20, STAKE=1001`), runs
canonical trajectories across every terminal outcome class (Won, CapReached with
leader & tie, Cancelled 1 & 2, Forfeited masks 1..7 in Commit & Reveal, MoveDefaulted
timeout Poke, Push clamp at 0), and emits `ingots/outlier_core/src/oracle_conformance_tests.fe`.
"""

from __future__ import annotations

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "oracle"))

import outlier_model as M  # noqa: E402

M.FINISH = 4
M.PUSH = 1
M.ROUND_CAP = 20
M.STAKE = 1001


def generate_fe_test_file() -> str:
    # Verify oracle predictions for key trajectories at shipping parameters
    # 1. All 7 forfeit masks at STAKE=1001
    forfeit_cases = []
    for mask in range(1, 8):
        pay = M.settle(("FORFEIT", mask), M.STAKE)
        forfeit_cases.append((mask, pay))

    # 2. Cancelled for joined=1, 2
    cancel_cases = [(j, M.settle(("CANCEL", j), M.STAKE)) for j in (1, 2)]

    # 3. CapReached for None, 0, 1, 2
    cap_cases = [(ldr, M.settle(("CAP", ldr), M.STAKE)) for ldr in (None, 0, 1, 2)]

    lines = [
        "// AUTO-GENERATED by `scripts/gen_oracle_tests.py` from `oracle/outlier_model.py`.",
        "// Do not hand-edit; run `python3 scripts/gen_oracle_tests.py` to regenerate.",
        "",
        "use ingot::{",
        "    COMMIT_WINDOW, Colour, FINISH, GameResult, GameState, Input, JOIN_WINDOW,",
        "    MOVE_WINDOW, Move, Phase, REVEAL_WINDOW, ROUND_CAP, Seat, StepCtx, StepError,",
        "    StepOut, commitment, settle, step,",
        "}",
        "",
        "fn unwrap_ok(_ res: Result<StepError, StepOut>) -> StepOut {",
        "    match res {",
        "        Result::Ok(o) => o,",
        "        Result::Err(_) => {",
        "            assert!(false)",
        "            StepOut {",
        "                state: GameState::new(0),",
        "                input_event: ingot::InputEvent::Poked { caller: 0 },",
        "                digest: 0,",
        "                finished: false,",
        "                payouts: [0, 0, 0],",
        "            }",
        "        }",
        "    }",
        "}",
        "",
        "fn join_three(_ stake: u256, _ table: u256) -> StepOut {",
        "    let s0 = GameState::new(stake)",
        "    let o1 = unwrap_ok(step(s0, 0, Input::Join, StepCtx { now: 100, caller: 0x10, table, stake_paid: stake }))",
        "    let o2 = unwrap_ok(step(o1.state, o1.digest, Input::Join, StepCtx { now: 110, caller: 0x20, table, stake_paid: stake }))",
        "    unwrap_ok(step(o2.state, o2.digest, Input::Join, StepCtx { now: 120, caller: 0x30, table, stake_paid: stake }))",
        "}",
        "",
        "fn play_round(",
        "    _ cur: StepOut,",
        "    _ table: u256,",
        "    _ ts: u256,",
        "    _ c0: u8,",
        "    _ c1: u8,",
        "    _ c2: u8,",
        ") -> StepOut {",
        "    let rnd = cur.state.round as u256",
        "    let gid = cur.state.game_id",
        "    let col0 = match Colour::from_u8(c0) { Option::Some(c) => c, Option::None => Colour::Red }",
        "    let col1 = match Colour::from_u8(c1) { Option::Some(c) => c, Option::None => Colour::Red }",
        "    let col2 = match Colour::from_u8(c2) { Option::Some(c) => c, Option::None => Colour::Red }",
        "    let h0 = commitment(table, game_id: gid, round: rnd, seat: Seat::s0(), colour: col0, nonce: rnd * 10 + 1)",
        "    let h1 = commitment(table, game_id: gid, round: rnd, seat: Seat::s1(), colour: col1, nonce: rnd * 10 + 2)",
        "    let h2 = commitment(table, game_id: gid, round: rnd, seat: Seat::s2(), colour: col2, nonce: rnd * 10 + 3)",
        "    let k0 = unwrap_ok(step(cur.state, cur.digest, Input::Commit { hash: h0 }, StepCtx { now: ts, caller: 0x10, table, stake_paid: 0 }))",
        "    let k1 = unwrap_ok(step(k0.state, k0.digest, Input::Commit { hash: h1 }, StepCtx { now: ts, caller: 0x20, table, stake_paid: 0 }))",
        "    let k2 = unwrap_ok(step(k1.state, k1.digest, Input::Commit { hash: h2 }, StepCtx { now: ts, caller: 0x30, table, stake_paid: 0 }))",
        "    let r0 = unwrap_ok(step(k2.state, k2.digest, Input::Reveal { colour_raw: c0, nonce: rnd * 10 + 1 }, StepCtx { now: ts + 1, caller: 0x10, table, stake_paid: 0 }))",
        "    let r1 = unwrap_ok(step(r0.state, r0.digest, Input::Reveal { colour_raw: c1, nonce: rnd * 10 + 2 }, StepCtx { now: ts + 1, caller: 0x20, table, stake_paid: 0 }))",
        "    unwrap_ok(step(r1.state, r1.digest, Input::Reveal { colour_raw: c2, nonce: rnd * 10 + 3 }, StepCtx { now: ts + 1, caller: 0x30, table, stake_paid: 0 }))",
        "}",
        "",
        "#[test]",
        "fn test_oracle_conformance_forfeits_and_cancels() {",
        f"    let stake: u256 = {M.STAKE}",
        "    let table: u256 = 0xCAFE",
    ]

    for j, pay in cancel_cases:
        lines.append(f"    // Oracle Cancel(joined={j}) -> {pay}")
        lines.append("    let s0 = GameState::new(stake)")
        lines.append(
            "    var cur = unwrap_ok(step(s0, 0, Input::Join, StepCtx { now: 100, caller: 0x10, table, stake_paid: stake }))"
        )
        if j == 2:
            lines.append(
                "    cur = unwrap_ok(step(cur.state, cur.digest, Input::Join, StepCtx { now: 110, caller: 0x20, table, stake_paid: stake }))"
            )
        lines.append(
            "    let fin = unwrap_ok(step(cur.state, cur.digest, Input::Poke, StepCtx { now: 100 + JOIN_WINDOW + 1, caller: 0x99, table, stake_paid: 0 }))"
        )
        lines.append("    assert!(fin.finished)")
        lines.append(
            f"    assert!(fin.payouts[0] == {pay[0]} && fin.payouts[1] == {pay[1]} && fin.payouts[2] == {pay[2]})"
        )

    for mask, pay in forfeit_cases:
        lines.append(f"    // Oracle Commit-phase Forfeit(mask={mask}) -> {pay}")
        lines.append("    var c_step = join_three(stake, table)")
        for seat_i, caller in ((0, "0x10"), (1, "0x20"), (2, "0x30")):
            if ((mask >> seat_i) & 1) == 0:
                lines.append(
                    f"    c_step = unwrap_ok(step(c_step.state, c_step.digest, Input::Commit {{ hash: {100 + seat_i} }}, StepCtx {{ now: 200, caller: {caller}, table, stake_paid: 0 }}))"
                )
        lines.append(
            "    let f_out = unwrap_ok(step(c_step.state, c_step.digest, Input::Poke, StepCtx { now: 120 + COMMIT_WINDOW + 1, caller: 0x99, table, stake_paid: 0 }))"
        )
        lines.append("    assert!(f_out.finished)")
        lines.append(
            f"    assert!(f_out.payouts[0] == {pay[0]} && f_out.payouts[1] == {pay[1]} && f_out.payouts[2] == {pay[2]})"
        )

    lines += [
        "}",
        "",
        "#[test]",
        "fn test_oracle_conformance_multi_round_win_timeout_move_and_cap() {",
        f"    let stake: u256 = {M.STAKE}",
        "    let table: u256 = 0xBEEF",
        "    var cur = join_three(stake, table)",
        "    var ts: u256 = 200",
        "",
        "    // Round 1: S0 wins (Blue=1 vs Red=0, Red=0), pushes S1 at 0 (saturates at 0)",
        "    cur = play_round(cur, table, ts, 1, 0, 0)",
        "    cur = unwrap_ok(step(cur.state, cur.digest, Input::MoveInput { mv: Move::Push { target: Seat::s1() } }, StepCtx { now: ts + 2, caller: 0x10, table, stake_paid: 0 }))",
        "    assert!(cur.state.positions.p0.to_u8() == 0 && cur.state.positions.p1.to_u8() == 0)",
        "    ts = ts + 10",
        "",
        "    // Rounds 2..=5: S0 wins 4 times; on Round 5 S0 times out in WinnerMove -> Poke defaults to Advance -> S0 reaches FINISH(4) and wins!",
        "    var r: u8 = 0",
        "    while r < 3 {",
        "        cur = play_round(cur, table, ts, 2, 0, 0)",
        "        cur = unwrap_ok(step(cur.state, cur.digest, Input::MoveInput { mv: Move::Advance }, StepCtx { now: ts + 2, caller: 0x10, table, stake_paid: 0 }))",
        "        ts = ts + 10",
        "        r = r + 1",
        "    }",
        "    assert!(cur.state.positions.p0.to_u8() == FINISH - 1)",
        "    cur = play_round(cur, table, ts, 2, 0, 0)",
        "    // Timeout Poke on WinnerMove applies default Advance -> S0 reaches FINISH!",
        "    cur = unwrap_ok(step(cur.state, cur.digest, Input::Poke, StepCtx { now: ts + 1 + MOVE_WINDOW + 1, caller: 0x99, table, stake_paid: 0 }))",
        "    assert!(cur.finished)",
        f"    assert!(cur.payouts[0] == {M.STAKE * 3} && cur.payouts[1] == 0 && cur.payouts[2] == 0)",
        "",
        "    // Game #2: 20 NoWinner rounds (all-distinct 0,1,2) reach ROUND_CAP with tied 0,0,0 -> CapReached(None) refund",
        "    cur = join_three(stake, table)",
        "    ts = 200",
        "    var rnd: u8 = 1",
        "    while rnd <= ROUND_CAP {",
        "        cur = play_round(cur, table, ts, 0, 1, 2)",
        "        ts = ts + 10",
        "        rnd = rnd + 1",
        "    }",
        "    assert!(cur.finished)",
        f"    assert!(cur.payouts[0] == {M.STAKE} && cur.payouts[1] == {M.STAKE} && cur.payouts[2] == {M.STAKE})",
        "",
        "    // Game #3: 19 NoWinner rounds, then Round 20 (ROUND_CAP) S1 wins and advances to 1 (< FINISH) -> CapReached(Some(S1))",
        "    cur = join_three(stake, table)",
        "    ts = 200",
        "    var rnd3: u8 = 1",
        "    while rnd3 < ROUND_CAP {",
        "        cur = play_round(cur, table, ts, 0, 0, 0)",
        "        ts = ts + 10",
        "        rnd3 = rnd3 + 1",
        "    }",
        "    cur = play_round(cur, table, ts, 0, 1, 0)",
        "    cur = unwrap_ok(step(cur.state, cur.digest, Input::MoveInput { mv: Move::Advance }, StepCtx { now: ts + 2, caller: 0x20, table, stake_paid: 0 }))",
        "    assert!(cur.finished)",
        f"    assert!(cur.payouts[0] == 0 && cur.payouts[1] == {M.STAKE * 3} && cur.payouts[2] == 0)",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    out_path = os.path.join(ROOT, "ingots", "outlier_core", "src", "oracle_conformance_tests.fe")
    content = generate_fe_test_file()
    with open(out_path, "w") as f:
        f.write(content)
    print(f"Wrote {out_path}")


if __name__ == "__main__":
    main()
